CREATE TABLE room_name_pool (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	generated BOOLEAN NOT NULL DEFAULT TRUE,
	consumed_at TIMESTAMP
);

WITH constants_q AS (
	SELECT
		519::BIGINT AS word_count,
		(519 * 518 * 517)::BIGINT AS permutation_count
),
ranks_q AS (
	SELECT
		series_q.series_id,
		(
			(series_q.series_id * 104729 + 7919) %
			constants_q.permutation_count
		)::BIGINT AS permutation_rank,
		constants_q.word_count
	FROM generate_series(0::BIGINT, 999999::BIGINT) AS series_q(series_id)
	CROSS JOIN constants_q
),
indexes_q AS (
	SELECT
		series_id,
		(permutation_rank / ((word_count - 1) * (word_count - 2)))::INTEGER AS first_index,
		((permutation_rank / (word_count - 2)) % (word_count - 1))::INTEGER AS second_rank,
		(permutation_rank % (word_count - 2))::INTEGER AS third_rank
	FROM ranks_q
),
second_indexes_q AS (
	SELECT
		series_id,
		first_index,
		second_rank + CASE WHEN second_rank >= first_index THEN 1 ELSE 0 END AS second_index,
		third_rank
	FROM indexes_q
),
word_indexes_q AS (
	SELECT
		series_id,
		first_index,
		second_index,
		third_rank
			+ CASE
				WHEN third_rank >= LEAST(first_index, second_index) THEN 1
				ELSE 0
			END
			+ CASE
				WHEN third_rank >= GREATEST(first_index, second_index) - 1 THEN 1
				ELSE 0
			END AS third_index
	FROM second_indexes_q
)
INSERT INTO room_name_pool (name)
SELECT first_word_q.word || '-' || second_word_q.word || '-' || third_word_q.word
FROM word_indexes_q
JOIN room_name_words first_word_q
ON first_word_q.id = word_indexes_q.first_index + 1
JOIN room_name_words second_word_q
ON second_word_q.id = word_indexes_q.second_index + 1
JOIN room_name_words third_word_q
ON third_word_q.id = word_indexes_q.third_index + 1
ORDER BY word_indexes_q.series_id;

CREATE UNIQUE INDEX room_name_pool_name_idx
ON room_name_pool (name);

INSERT INTO room_name_pool (name, generated, consumed_at)
SELECT rooms.id, FALSE, COALESCE(rooms.created_at, CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
FROM rooms
ON CONFLICT (name) DO UPDATE
SET consumed_at = EXCLUDED.consumed_at;

CREATE INDEX room_name_pool_available_id_idx
ON room_name_pool (id)
WHERE consumed_at IS NULL;

CREATE TABLE room_name_reservations (
	name TEXT PRIMARY KEY,
	token UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
	owner_id TEXT NOT NULL,
	created_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
	expires_at TIMESTAMP NOT NULL,
	CONSTRAINT room_name_reservations_owner_id_key UNIQUE (owner_id),
	CONSTRAINT room_name_reservations_expiry_check CHECK (expires_at > created_at)
);

CREATE INDEX room_name_reservations_expires_at_idx
ON room_name_reservations (expires_at);

